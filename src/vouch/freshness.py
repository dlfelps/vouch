"""Is each run still the output of the code and data it recorded? (SPEC §8)

A run is compared against the working tree by content hash -- no git needed:

* each recorded code unit is re-hashed semantically (comment/docstring edits are
  *cosmetic* and never make a run stale);
* each input is re-hashed (through the size/mtime cache);
* an input that is another run's artifact ties the two runs together: if the
  producer re-ran and its artifact changed, the consumer is stale; if the
  producer is stale, the consumer is *upstream-stale*;
* artifacts on disk that no longer match their recorded hash are *tampered*.

A person can accept a staleness they have reviewed (``vouch accept``). The
acceptance names the exact current hashes, so the next edit re-opens it.
"""

from __future__ import annotations

import dataclasses
import datetime as _dt
import getpass
import json
import subprocess
from pathlib import Path
from typing import Any

from .config import Config
from .hashing import HashCache, mode_of
from .units import raw_hash, units_from_file

ERROR_STATES = ("incomplete", "tampered", "stale", "upstream-stale")
LEDGER = "accepted.toml"


@dataclasses.dataclass
class Reason:
    kind: str          # unit-changed unit-missing file-missing unparseable input-changed
                       # input-regenerated upstream tampered absent-input absent-artifact
                       # env-drift cosmetic incomplete
    subject: str       # e.g. "src/models.py::score", "data/x.csv", run id
    detail: str = ""
    current: str | None = None      # current hash, what an acceptance records

    @property
    def token(self) -> str:
        """The ledger key for an acceptable reason."""
        return {"unit-changed": "unit", "unit-missing": "unit", "file-missing": "unit",
                "unparseable": "unit", "input-changed": "input",
                "input-regenerated": "regen"}.get(self.kind, self.kind) + ":" + self.subject


OWN_STALE = ("unit-changed", "unit-missing", "file-missing", "unparseable", "input-changed",
             "input-regenerated")


@dataclasses.dataclass
class RunState:
    run: str
    state: str                               # fresh cosmetic accepted stale upstream-stale
                                             # tampered incomplete
    reasons: list[Reason]
    command: str
    acceptance: dict | None = None
    recorded: dict | None = None

    def of(self, *kinds: str) -> list[Reason]:
        return [r for r in self.reasons if r.kind in kinds]

    @property
    def is_error(self) -> bool:
        return self.state in ERROR_STATES

    def summary(self) -> str:
        if self.state == "fresh":
            return "fresh"
        if self.state == "cosmetic":
            return "fresh (files changed, but not in anything this run executed)"
        if self.state == "accepted":
            a = self.acceptance or {}
            return f"accepted: {a.get('why', '')}".strip()
        if self.state == "incomplete":
            return "the run did not finish"
        if self.state == "upstream-stale":
            ups = sorted({r.subject for r in self.of("upstream")})
            return f"reads the output of stale run{'s' if len(ups) > 1 else ''} {', '.join(ups)}"
        if self.state == "tampered":
            return "artifact changed outside a run: " + ", ".join(r.subject for r in self.of("tampered"))
        parts = []
        units = [r.subject for r in self.of("unit-changed", "unit-missing", "file-missing",
                                              "unparseable")]
        if units:
            parts.append(_list(units) + " changed")
        ins = [r.subject for r in self.of("input-changed")]
        if ins:
            parts.append("input " + _list(ins) + " changed")
        regen = [r for r in self.of("input-regenerated")]
        if regen:
            parts.append("input " + _list([r.subject for r in regen]) + " was regenerated by "
                         + _list(sorted({r.detail for r in regen})))
        return "; ".join(parts) + " since the run"


def _list(items: list[str], n: int = 3) -> str:
    return ", ".join(items[:n]) + (f" (+{len(items) - n} more)" if len(items) > n else "")


# ---------------------------------------------------------------------------
# the accept ledger (.vouch/accepted.toml)
# ---------------------------------------------------------------------------

def load_ledger(cfg: Config) -> dict[str, dict]:
    path = cfg.store / LEDGER
    if not path.is_file():
        return {}
    import sys
    if sys.version_info >= (3, 11):
        import tomllib
    else:  # pragma: no cover
        import tomli as tomllib
    with open(path, "rb") as fh:
        data = tomllib.load(fh)
    return {e["run"]: e for e in data.get("accept", []) if "run" in e}


def _toml_str(s: str) -> str:
    return json.dumps(str(s), ensure_ascii=False)          # TOML basic strings match JSON's


def write_ledger(cfg: Config, entries: dict[str, dict]) -> None:
    lines = ["# Stale runs reviewed and accepted by hand (`vouch accept`). Each acceptance",
             "# clears its run only for the exact hashes listed; the next edit re-opens it.", ""]
    for run in sorted(entries):
        e = entries[run]
        lines += ["[[accept]]", f"run = {_toml_str(run)}", f"why = {_toml_str(e.get('why', ''))}",
                  f"by = {_toml_str(e.get('by', ''))}", f"date = {_toml_str(e.get('date', ''))}",
                  "[accept.hashes]"]
        lines += [f"{_toml_str(k)} = {_toml_str(v)}" for k, v in sorted(e.get("hashes", {}).items())]
        lines.append("")
    cfg.store.mkdir(parents=True, exist_ok=True)
    (cfg.store / LEDGER).write_text("\n".join(lines), encoding="utf-8", newline="\n")


def who() -> str:
    try:
        r = subprocess.run(["git", "config", "user.name"], capture_output=True, text=True, timeout=5)
        if r.returncode == 0 and r.stdout.strip():
            return r.stdout.strip()
    except (OSError, subprocess.SubprocessError):
        pass
    try:
        return getpass.getuser()
    except Exception:  # pragma: no cover
        return "unknown"


def now() -> str:
    return _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


